"""Day 4 scenario matrix: one test (or more) per required scenario, each with a ground truth written beforehand.

Ground truth = the rule ids that SHOULD be flagged for a label change, decided from what the change means, not from
engine output. A flagged rule that is not expected is a false positive; an expected rule not flagged is a false negative.
The labels are synthetic and generated by this project, so these tests show regression safety, not real-world accuracy.
"""
from dataclasses import replace

import pymupdf
import pytest

from labelguard import config
from labelguard.extraction.pdf_text import ExtractionError
from labelguard.ingestion import ingest_pdf, validate_upload
from labelguard.rules.models import RESULT_NOT_EVALUATED
from labelguard.samples.synthetic_labels import APPROVED as A
from labelguard.samples.synthetic_labels import INCOMPLETE, make_scanned_copy, render_label_pdf
from labelguard.verification import verify_pair


@pytest.fixture
def pair(tmp_path):
    def run(revised_spec, approved_spec=A, **options):
        a = render_label_pdf(approved_spec, tmp_path / "a.pdf").read_bytes()
        r = render_label_pdf(revised_spec, tmp_path / "r.pdf").read_bytes()
        return verify_pair((a, "approved.pdf"), (r, "revised.pdf"), **options)

    return run


def flagged_ids(result):
    return {f.rule_id for f in result.report.flagged}


# 1. identical versions ----------------------------------------------------------------------------------------------
def test_identical_label_versions_have_no_findings(pair):
    result = pair(A)
    assert result.report.flagged == ()
    comparison = result.analysis.comparison
    assert comparison.changed_fields == 0 and comparison.text_changes == () and comparison.moved_lines == 0
    assert comparison.matching_fields >= 5  # the fields really were read and compared, not skipped


# 2. changed product identifier ------------------------------------------------------------------------------------
def test_changed_product_identifier_is_flagged_with_both_values_as_evidence(pair):
    result = pair(replace(A, ref="NW-IV200-99"))
    assert flagged_ids(result) == {"R-ID-001"}
    finding = result.report.flagged[0]
    assert finding.severity == "critical_review" and finding.approved_value == "NW-IV200-20" and finding.revised_value == "NW-IV200-99"
    sources = {e.source for e in finding.evidence}
    assert {"approved", "revised"} <= sources and all(e.page == 1 for e in finding.evidence)
    assert finding.recommended_action


# 3. removed safety warning ------------------------------------------------------------------------------------------
def test_removed_safety_warning_is_flagged_and_quotes_the_removed_text(pair):
    result = pair(replace(A, warnings=A.warnings[:1] + A.warnings[2:]))
    assert flagged_ids(result) == {"R-WARN-001"}
    finding = result.report.flagged[0]
    assert finding.severity == "critical_review"
    assert any("Do not use if package is damaged" in e.text for e in finding.evidence)


# 4. missing configured required field -----------------------------------------------------------------------------
def test_missing_required_field_is_flagged(pair):
    assert flagged_ids(pair(replace(A, lot=None))) == {"R-REQ-005"}


def test_label_missing_several_required_fields_flags_each_and_never_guesses(pair):
    result = pair(INCOMPLETE)
    assert {"R-REQ-004", "R-REQ-005"} <= flagged_ids(result)  # manufacturer and lot
    fields = result.analysis.revised.fields
    assert not fields.get("lot_number").detected and not fields.get("manufacturer").detected  # reported missing, not guessed
    assert fields.get("product_identifier").detected  # fields that ARE printed are still found


# 5. added harmless text ---------------------------------------------------------------------------------------------
def test_added_harmless_text_is_reported_at_low_priority_only(pair):
    result = pair(replace(A, extra_lines=("Distributed by Example Distribution Co.",)))
    assert flagged_ids(result) == {"R-TEXT-001"}
    assert result.report.flagged[0].severity in ("low", "informational", "medium")  # never critical/high


# 6. date mismatch -----------------------------------------------------------------------------------------------------
def test_changed_expiry_date_is_flagged(pair):
    assert flagged_ids(pair(replace(A, expiry="2027-06-30"))) == {"R-DATE-001"}


def test_expiry_before_manufacture_is_flagged_as_inconsistent(pair):
    assert flagged_ids(pair(replace(A, expiry="2023-01-01"))) == {"R-DATE-001", "R-DATE-003"}


# 7. multi-page PDF ------------------------------------------------------------------------------------------------------
def test_added_page_is_flagged(pair):
    result = pair(replace(A, extra_pages=(("Instructions", "Open the pouch.", "Connect the line."),)))
    assert flagged_ids(result) == {"R-PAGE-001", "R-TEXT-001"}
    assert result.analysis.revised.document.page_count == 2


def test_identical_multi_page_labels_are_clean_and_page_text_is_read(pair):
    spec = replace(A, extra_pages=(("Instructions", "Open the pouch.", "Connect the line."), ("Disposal", "Dispose per local rules.")))
    result = pair(spec, approved_spec=spec)
    assert result.report.flagged == () and result.analysis.revised.document.page_count == 3
    assert "Connect the line" in result.analysis.revised.document.full_text


# 8. scanned PDF, OCR available ----------------------------------------------------------------------------------------
def test_scanned_copy_with_ocr_has_no_false_identifier_or_warning_findings(tmp_path, tesseract_available):
    if not tesseract_available:
        pytest.skip("Tesseract OCR is not installed here")
    a = render_label_pdf(A, tmp_path / "a.pdf").read_bytes()
    result = verify_pair((a, "approved.pdf"), (make_scanned_copy(a), "scan.pdf"))
    assert result.analysis.revised.document.ocr_pages == [1]  # the text came from OCR
    # Ground truth: the scan IS the approved label, so nothing may be reported as changed.
    assert result.report.flagged == (), [f.title for f in result.report.flagged]
    # The artwork cannot be compared pixel by pixel against a scan, and must say so instead of passing.
    assert {o.rule_id: o.outcome for o in result.report.outcomes}["R-ART-001"] == "not_evaluated"
    assert any("OCR" in n.message for n in result.analysis.revised.ingestion.notes)  # the reviewer is told it was OCR


# 9. scanned PDF, OCR unavailable ------------------------------------------------------------------------------------
def test_scanned_copy_without_ocr_is_not_verified_and_never_a_pass(tmp_path):
    a = render_label_pdf(A, tmp_path / "a.pdf").read_bytes()
    result = verify_pair((a, "approved.pdf"), (make_scanned_copy(a), "scan.pdf"), use_ocr=False)
    assert result.report.flagged == ()  # no invented removals
    readability = [f for f in result.report.findings if f.rule_id == "R-READ-001"]
    assert len(readability) == 1 and readability[0].result == RESULT_NOT_EVALUATED
    assert {o.rule_id: o.outcome for o in result.report.outcomes}["R-WARN-001"] == "not_evaluated"


# 10. malformed or encrypted PDF -----------------------------------------------------------------------------------
def encrypted():
    doc = pymupdf.open()
    doc.new_page().insert_text((72, 72), "secret label text")
    return doc.tobytes(encryption=pymupdf.PDF_ENCRYPT_AES_256, user_pw="u", owner_pw="o")


@pytest.mark.parametrize("name, data, message", [
    ("label.pdf", b"", "empty"),
    ("label.pdf", b"not a pdf at all", "does not look like a PDF"),
    ("label.pdf", b"%PDF-1.7\ngarbage garbage", None),
    ("label.txt", b"%PDF-1.7", "Unsupported file type"),
    ("label.pdf", encrypted(), "password"),
])
def test_malformed_or_encrypted_files_are_rejected_before_processing(name, data, message):
    with pytest.raises(ExtractionError, match=message):
        validate_upload(name, data)
    with pytest.raises(ExtractionError):
        ingest_pdf(data, name)


def test_uploading_an_encrypted_file_in_the_app_shows_an_error_and_blocks_analysis():
    from test_app_smoke import new_app, open_page, texts, upload

    at = open_page(new_app(), "Upload & Analyze")
    upload(at, "approved", "locked.pdf", encrypted())
    assert not at.exception and "password" in texts(at.error).lower()
    assert at.button(key="start_analysis").disabled


def test_page_and_size_limits_are_enforced(approved_pdf, monkeypatch):
    monkeypatch.setattr(config, "MAX_PAGES", 1)
    two_pages = render_label_pdf(replace(A, extra_pages=(("x", "y"),)), approved_pdf.parent / "two.pdf").read_bytes()
    with pytest.raises(ExtractionError, match="limit is 1"):
        validate_upload("two.pdf", two_pages)
    monkeypatch.setattr(config, "MAX_UPLOAD_MB", 0)
    with pytest.raises(ExtractionError, match="limit"):
        validate_upload("a.pdf", approved_pdf.read_bytes())


# 11. page layout change ----------------------------------------------------------------------------------------------------
def test_layout_change_is_flagged_by_the_artwork_rule_and_not_by_any_text_rule(pair):
    for spec in (replace(A, logo_x_mm=100.0), replace(A, band_color="#8A2B2B")):
        assert flagged_ids(pair(spec)) == {"R-ART-001"}


def test_layout_change_is_not_verified_rather_than_passed_when_vision_is_off(pair):
    result = pair(replace(A, logo_x_mm=100.0), run_visual=False)
    assert "R-ART-001" not in flagged_ids(result)
    assert {o.rule_id: o.outcome for o in result.report.outcomes}["R-ART-001"] != "passed"
