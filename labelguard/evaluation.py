"""Synthetic evaluation corpus: label pairs with known expected findings, and precision/recall.

Run it with:  python -m labelguard.evaluation

IMPORTANT: the corpus is small, fictional and generated by the same code that renders the
labels. The numbers below measure regression (does a change to the engine break behaviour we
defined as correct?). They are NOT an estimate of accuracy on real labels.

Expected outcomes are defined here, from what each change means, before looking at engine
output. A flagged rule that is not expected is a false positive; an expected rule that is
not flagged is a false negative. Not-evaluated items are informational and are not counted.
"""
