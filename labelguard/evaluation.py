"""Synthetic evaluation corpus: label pairs with known expected findings, and precision/recall.

Run it with:  python -m labelguard.evaluation

IMPORTANT: the corpus is small, fictional and generated by the same code that renders the
labels. The numbers below measure regression (does a change to the engine break behaviour we
defined as correct?). They are NOT an estimate of accuracy on real labels.

Expected outcomes are defined here, from what each change means, before looking at engine
output. A flagged rule that is not expected is a false positive; an expected rule that is
not flagged is a false negative. Not-evaluated items are informational and are not counted.
"""
from __future__ import annotations

import tempfile
from dataclasses import dataclass, replace
from pathlib import Path

from labelguard.samples.synthetic_labels import APPROVED as A
from labelguard.samples.synthetic_labels import LabelSpec, render_label_pdf
from labelguard.verification import verify_pair


@dataclass(frozen=True)
class Case:
    name: str
    revised: LabelSpec
    expected: frozenset[str]  # rule ids that must be flagged, and no others
    note: str = ""


def _c(name: str, revised: LabelSpec, *rules: str, note: str = "") -> Case:
    return Case(name, revised, frozenset(rules), note)


CORPUS: tuple[Case, ...] = (
    _c("unchanged label", A, note="no differences must give no findings"),
    _c("REF changed", replace(A, ref="NW-IV200-99"), "R-ID-001"),
    _c("UDI-DI changed (text and barcode)", replace(A, udi_di_body="0890123456802"),
       "R-ID-002", "R-ID-003", "R-ART-001"),
    _c("warning removed", replace(A, warnings=A.warnings[:1] + A.warnings[2:]), "R-WARN-001"),
    _c("warning added", replace(A, warnings=A.warnings + ("Do not resterilize.",)), "R-WARN-003", "R-STER-002"),
    _c("warning reworded", replace(A, warnings=("Single use only.",) + A.warnings[1:]), "R-WARN-002"),
    _c("storage range changed", replace(A, storage="Store between 5 and 40 degrees C. Keep dry."), "R-STOR-001"),
    _c("sterilization method changed", replace(A, sterility="STERILE R"), "R-STER-001"),
    _c("lot changed", replace(A, lot="B25-0001"), "R-LOT-001"),
    _c("expiry date changed", replace(A, expiry="2027-06-30"), "R-DATE-001"),
    _c("manufacturer changed", replace(A, manufacturer="Southwind Medical Ltd."), "R-MFR-001"),
    _c("lot missing from revised", replace(A, lot=None), "R-REQ-005"),
    _c("manufacturer missing from revised", replace(A, manufacturer=None), "R-REQ-004"),
    _c("harmless added line", replace(A, extra_lines=("Distributed by Example Distribution Co.",)), "R-TEXT-001"),
    _c("warnings reordered", replace(A, warnings=(A.warnings[1], A.warnings[0]) + A.warnings[2:]),
       note="same words in another order is not a change"),
    _c("header colour changed", replace(A, band_color="#8A2B2B"), "R-ART-001"),
    _c("logo moved", replace(A, logo_x_mm=100.0), "R-ART-001"),
    _c("extra page added", replace(A, extra_pages=(("Instructions", "Open the pouch.", "Connect the line."),)),
       "R-PAGE-001", "R-TEXT-001"),
    _c("barcode disagrees with printed UDI", replace(A, barcode_value="0109999999999994"),
       "R-ID-003", "R-ID-004", "R-ART-001"),
    _c("UDI check digit invalid", replace(A, udi_text="(01)08901234567899"),
       "R-ID-002", "R-ID-004", "R-ID-005"),
    _c("expiry before manufacture date", replace(A, expiry="2023-01-01"), "R-DATE-001", "R-DATE-003"),
)


@dataclass(frozen=True)
class CaseResult:
    case: Case
    flagged: frozenset[str]

    @property
    def true_positives(self) -> frozenset[str]:
        return self.flagged & self.case.expected

    @property
    def false_positives(self) -> frozenset[str]:
        return self.flagged - self.case.expected

    @property
    def false_negatives(self) -> frozenset[str]:
        return self.case.expected - self.flagged


@dataclass(frozen=True)
class Metrics:
    tp: int
    fp: int
    fn: int
    cases: int
    exact_cases: int

    @property
    def precision(self) -> float:
        return self.tp / (self.tp + self.fp) if self.tp + self.fp else 1.0

    @property
    def recall(self) -> float:
        return self.tp / (self.tp + self.fn) if self.tp + self.fn else 1.0


def run_corpus(corpus: tuple[Case, ...] = CORPUS, *, run_visual: bool = True) -> list[CaseResult]:
    results = []
    with tempfile.TemporaryDirectory() as folder:
        root = Path(folder)
        approved = render_label_pdf(A, root / "approved.pdf").read_bytes()
        for case in corpus:
            revised = render_label_pdf(case.revised, root / "revised.pdf").read_bytes()
            report = verify_pair(
                (approved, "approved.pdf"), (revised, "revised.pdf"), run_visual=run_visual, run_barcodes=True
            ).report
            results.append(CaseResult(case, frozenset(f.rule_id for f in report.flagged)))
    return results


def compute_metrics(results: list[CaseResult]) -> Metrics:
    return Metrics(
        tp=sum(len(r.true_positives) for r in results),
        fp=sum(len(r.false_positives) for r in results),
        fn=sum(len(r.false_negatives) for r in results),
        cases=len(results),
        exact_cases=sum(1 for r in results if not r.false_positives and not r.false_negatives),
    )


def format_report(results: list[CaseResult]) -> str:
    metrics = compute_metrics(results)
    lines = [f"{'Case':<40} {'TP':>3} {'FP':>3} {'FN':>3}  Detail"]
    for r in results:
        detail = []
        if r.false_positives:
            detail.append("unexpected: " + ", ".join(sorted(r.false_positives)))
        if r.false_negatives:
            detail.append("missed: " + ", ".join(sorted(r.false_negatives)))
        lines.append(
            f"{r.case.name:<40} {len(r.true_positives):>3} {len(r.false_positives):>3} "
            f"{len(r.false_negatives):>3}  {'; '.join(detail)}"
        )
    lines += [
        "",
        f"Cases matching exactly: {metrics.exact_cases}/{metrics.cases}",
        f"Precision: {metrics.precision:.3f}   Recall: {metrics.recall:.3f}  "
        f"(TP {metrics.tp}, FP {metrics.fp}, FN {metrics.fn})",
        "Synthetic corpus: measures regression, not accuracy on real labels.",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(format_report(run_corpus()))
